-- FitTrack — acompanhamento de treinos
-- =========================================================================================
--
-- exercises.user_id is null       -> base compartilhada (carregada por supabase-exercises.sql)
-- exercises.user_id = auth.uid()  -> exercício criado pelo próprio usuário
-- workout_plans: uma ficha por conta. Os treinos (A, B, C...) e a ordem dos exercícios ficam
--   num jsonb, gravado de uma vez: reordenar ou trocar a divisão nunca deixa a ficha pela metade.
--   A letra de cada treino é a posição dele na lista, não um dado salvo.
-- exercise_logs: carga, séries e repetições de um exercício num dia. Apontam para o exercício,
--   não para a ficha, então mudar a ficha não apaga histórico.

create table if not exists public.exercises (id bigint generated by default as identity primary key, user_id uuid references auth.users(id) on delete cascade, slug text, name text not null, name_en text, name_es text, muscle_group text not null, created_at timestamptz not null default now());
create table if not exists public.workout_plans (user_id uuid primary key references auth.users(id) on delete cascade, workouts jsonb not null default '[]'::jsonb, anchor_date date not null default current_date, anchor_index integer not null default 0, updated_at timestamptz not null default now());
create table if not exists public.exercise_logs (id bigint generated by default as identity primary key, user_id uuid not null references auth.users(id) on delete cascade, exercise_id bigint not null references public.exercises(id) on delete cascade, date date not null, weight_kg numeric not null, sets integer not null, reps integer not null, created_at timestamptz not null default now());

-- A ficha passou a aceitar dias de descanso: até 14 posições (treinos + descansos). Remove
-- a regra antiga para que o bloco abaixo a recrie com os limites novos.
alter table public.workout_plans drop constraint if exists workout_plans_shape_valid;

do $$ begin
	if not exists (select 1 from pg_constraint where conname = 'exercises_name_length') then alter table public.exercises add constraint exercises_name_length check (char_length(name) between 1 and 120 and (name_en is null or char_length(name_en) between 1 and 120) and (name_es is null or char_length(name_es) between 1 and 120)); end if;
	if not exists (select 1 from pg_constraint where conname = 'exercises_muscle_valid') then alter table public.exercises add constraint exercises_muscle_valid check (muscle_group in ('chest', 'back', 'shoulders', 'traps', 'biceps', 'triceps', 'forearms', 'abs', 'quads', 'hamstrings', 'glutes', 'calves', 'full_body')); end if;
	-- Só a base compartilhada tem slug: é por ele que os modelos de ficha encontram os exercícios.
	if not exists (select 1 from pg_constraint where conname = 'exercises_slug_shared_only') then alter table public.exercises add constraint exercises_slug_shared_only check (slug is null or user_id is null); end if;
	-- Até 14 posições (no máximo 7 treinos, A a G, mais os descansos); a referência aponta para uma delas.
	if not exists (select 1 from pg_constraint where conname = 'workout_plans_shape_valid') then alter table public.workout_plans add constraint workout_plans_shape_valid check (jsonb_typeof(workouts) = 'array' and jsonb_array_length(workouts) between 1 and 14 and anchor_index between 0 and 13 and pg_column_size(workouts) < 65536); end if;
	-- 0 kg = só o peso do corpo (barra fixa, prancha...).
	if not exists (select 1 from pg_constraint where conname = 'exercise_logs_values_valid') then alter table public.exercise_logs add constraint exercise_logs_values_valid check (weight_kg between 0 and 1000 and sets between 1 and 20 and reps between 1 and 200); end if;
end $$;

