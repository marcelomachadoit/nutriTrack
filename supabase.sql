-- NutriTrack — schema completo. Idempotente: pode ser executado novamente com segurança.
--
-- Modelo de alimentos:
--   foods.user_id is null  -> base nutricional compartilhada (somente leitura para o cliente)
--   foods.user_id = auth.uid() -> alimento criado pelo próprio usuário (ele edita e apaga)
-- Receitas são sempre privadas do usuário que as criou.

create table if not exists public.profiles (id uuid primary key references auth.users(id) on delete cascade, name text not null, age integer, weight numeric, height numeric, goal text, created_at timestamptz not null default now());
create table if not exists public.foods (id bigint generated by default as identity primary key, name text not null, calories numeric not null, protein numeric not null default 0, carbohydrates numeric not null default 0, fat numeric not null default 0, serving_size numeric not null default 100, base_unit text not null default 'g', portion_label text, portion_amount numeric, created_at timestamptz not null default now());
create table if not exists public.meals (id bigint generated by default as identity primary key, user_id uuid not null references auth.users(id) on delete cascade, food_id bigint not null references public.foods(id), quantity numeric not null, meal_type text not null, date date not null default current_date, created_at timestamptz not null default now());
create table if not exists public.recipes (id bigint generated by default as identity primary key, user_id uuid not null references auth.users(id) on delete cascade, name text not null, created_at timestamptz not null default now());
create table if not exists public.recipe_items (id bigint generated by default as identity primary key, recipe_id bigint not null references public.recipes(id) on delete cascade, food_id bigint not null references public.foods(id) on delete cascade, quantity numeric not null);
create table if not exists public.weight_logs (id bigint generated by default as identity primary key, user_id uuid not null references auth.users(id) on delete cascade, date date not null, weight_kg numeric not null, created_at timestamptz not null default now());
create table if not exists public.meal_slots (id bigint generated by default as identity primary key, user_id uuid not null references auth.users(id) on delete cascade, name text not null, icon text not null default 'utensils', position integer not null default 0, created_at timestamptz not null default now());

